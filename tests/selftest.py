#!/usr/bin/env python3
"""Protocol + planner self-test for hunt_obs_autoclip.py.

1. Replays the golden wire frames (tests/python-wire.json, generated by
   HuntOpenHighlights' original Python protobuf modules) against Session and
   asserts the replies are well-formed and successful where expected.
2. Runs the kill sequence (open group, 3 kills 5s apart, close) against
   ClipPlanner and asserts coalescing/throttling behavior.
3. Replays python-control-wire.json malformed/control-char frames; Session
   must either answer or raise a clean ValueError (no crash beyond that).

Run:  .venv/Scripts/python.exe tests/selftest.py
"""
from __future__ import annotations

import base64
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "protocol"))

import BusMessage_pb2 as bus_pb2
import sdk_pb2 as sdk_pb2
from hunt_obs_autoclip import ClipPlanner, Session

PASS, FAIL = [], []


def check(name: str, cond: bool, detail: str = ""):
    (PASS if cond else FAIL).append(name)
    print(f"  {'PASS' if cond else 'FAIL'}  {name}" + (f"  ({detail})" if detail and not cond else ""))


def parse_reply(payload: bytes) -> tuple[bus_pb2.BusMessage, sdk_pb2.SDKIPCResponse | None]:
    msg = bus_pb2.BusMessage()
    msg.ParseFromString(payload)
    inner = None
    if msg.HasField("generic") and msg.generic.data:
        inner = sdk_pb2.SDKIPCMessage()
        inner.ParseFromString(msg.generic.data)
    return msg, inner


def reply_ok(inner) -> bool:
    return (inner is not None and inner.WhichOneof("message") == "response"
            and inner.response.retval == 0)


def test_golden_frames():
    print("[1] golden wire frames (python-wire.json)")
    frames = json.loads((ROOT / "tests" / "python-wire.json").read_text(encoding="utf-8"))
    events: list[tuple] = []
    session = Session(client_pid=42,
                      on_highlight=lambda *a: events.append(a) or True,
                      log_fn=lambda m: None)

    by_name = {f["name"]: base64.b64decode(f["base64"]) for f in frames}

    # join -> expect 2 replies: bus ack (bus_peer SDKAPI) + joined envelope
    replies = [parse_reply(r) for r in
               [x.SerializeToString() for x in session.process(_parse(by_name["join"]))]]
    check("join: two replies", len(replies) == 2)
    check("join: bus_peer contains NvNode/SDKAPI",
          any(p.system == "NvNode" and p.module == "SDKAPI"
              for m, _ in replies for p in m.bus_peer))

    # create -> authorized, game name captured
    replies = [parse_reply(r) for r in
               [x.SerializeToString() for x in session.process(_parse(by_name["create"]))]]
    check("create: one reply, retval 0", len(replies) == 1 and reply_ok(replies[0][1]))
    check("create: GFE version reported",
          replies[0][1].response.createSDKInstanceResponse.installedGfeVersion != "")
    check("create: game name = Hunt: Showdown 1896",
          session.game_name == "Hunt: Showdown 1896")

    # configure -> HUNTER_KILLED + PLAYER_DOWNED registered
    session.process(_parse(by_name["configure"]))
    check("configure: definitions registered",
          session.definitions == {"HUNTER_KILLED", "PLAYER_DOWNED"})

    # open group
    session.process(_parse(by_name["open"]))
    check("open: match-1896 tracked", "match-1896" in session.groups)

    # THE kill frame
    replies = [parse_reply(r) for r in
               [x.SerializeToString() for x in session.process(_parse(by_name["kill"]))]]
    check("kill: retval 0", reply_ok(replies[0][1]))
    check("kill: on_highlight called with HUNTER_KILLED",
          len(events) == 1 and events[0][0] == "HUNTER_KILLED"
          and events[0][1] == "match-1896"
          and events[0][2] == -20000 and events[0][3] == 5000,
          detail=str(events))
    check("kill: group counter incremented", session.groups["match-1896"] == 1)

    # config/getUserConfig -> gameEnabled + our two events enabled
    replies = [parse_reply(r) for r in
               [x.SerializeToString() for x in session.process(_parse(by_name["config"]))]]
    cfg = replies[0][1].response.getUserConfigResponse
    check("config: gameEnabled", cfg.gameEnabled)
    check("config: both events userEnabled",
          {c.highlightId for c in cfg.highlightTable if c.userEnabled} == {"HUNTER_KILLED", "PLAYER_DOWNED"})

    # count
    replies = [parse_reply(r) for r in
               [x.SerializeToString() for x in session.process(_parse(by_name["count"]))]]
    check("count: 1 highlight in group",
          replies[0][1].response.getNumberOfHighlightsInGroupResponse.numberOfHighlights == 1)

    # close
    replies = [parse_reply(r) for r in
               [x.SerializeToString() for x in session.process(_parse(by_name["close"]))]]
    check("close: retval 0", reply_ok(replies[0][1]))


def _parse(payload: bytes) -> bus_pb2.BusMessage:
    msg = bus_pb2.BusMessage()
    msg.ParseFromString(payload)
    return msg


def test_unauthorized_gate():
    print("[2] unauthorized request gate")
    session = Session(42, lambda *a: True, lambda m: None)
    inner = sdk_pb2.SDKIPCMessage()
    req = sdk_pb2.SDKIPCRequest(version_major=1, version_minor=0, component=sdk_pb2.SDKComponent_SHARE)
    req.openGroupRequest.groupId = "x"
    inner.request.CopyFrom(req)
    frame = bus_pb2.BusMessage(
        uniqueid="u1", source_system="Hunt1896", source_module="GfeSDK")
    frame.generic.type = 1
    frame.generic.data = inner.SerializeToString()
    replies = session.process(frame)
    _, parsed = parse_reply(replies[0].SerializeToString())
    check("SDK request before create -> SDK_INSTANCE_REQUIRED",
          parsed.response.retstatus == "SDK_INSTANCE_REQUIRED", parsed.response.retstatus)


def test_control_frames():
    print("[3] control/malformed frames (python-control-wire.json)")
    frames = json.loads((ROOT / "tests" / "python-control-wire.json").read_text(encoding="utf-8"))
    session = Session(42, lambda *a: True, lambda m: None)
    ok = True
    detail = ""
    for f in frames:
        frame = bus_pb2.BusMessage()
        frame.ParseFromString(base64.b64decode(f["base64"]))
        try:
            replies = session.process(frame)
            for r in replies:
                parse_reply(r.SerializeToString())  # replies must re-parse
        except ValueError:
            pass  # clean refusal is acceptable for malformed input
        except Exception as exc:  # anything else is a bug
            ok = False
            detail = f"{f['name']}: {type(exc).__name__}: {exc}"
    check("control frames: handled or cleanly refused", ok, detail)


def test_planner():
    print("[4] ClipPlanner coalescing + throttling")
    planner = ClipPlanner({"HUNTER_KILLED", "PLAYER_DOWNED"}, coalesce_gap=15.0, min_interval=3.0)
    t0 = time.monotonic()

    class Clock:
        """Monkeypatch time.monotonic to simulate elapsed time deterministically."""
        now = 0.0

    real_monotonic = time.monotonic
    time.monotonic = lambda: t0 + Clock.now
    try:
        planner.register("HUNTER_KILLED", "match-1", -20000, 5000)   # t=0
        Clock.now = 5
        planner.register("HUNTER_KILLED", "match-1", -20000, 5000)   # t=5  -> merge
        Clock.now = 9
        planner.register("PLAYER_DOWNED", "match-1", -20000, 5000)   # t=9  -> merge
        fired = planner.poll_ready()
        check("3 kills within 15s: nothing fired yet (window open)", not fired)

        Clock.now = 10
        planner.register("HUNTER_KILLED", "match-2", -20000, 5000)   # new group, separate plan
        Clock.now = 24.1
        fired = planner.poll_ready()
        check("match-1 fires after its 15s window closes (1 fired)",
              len(fired) == 1 and fired[0]["group"] == "match-1", f"{len(fired)} fired")
        check("match-1 clip has 3 coalesced events",
              len(fired) == 1 and fired[0]["events"] == ["HUNTER_KILLED", "HUNTER_KILLED", "PLAYER_DOWNED"],
              str(fired[0]["events"] if fired else None))
        Clock.now = 25.1
        fired = planner.poll_ready()
        check("after 15s gap match-2 fires", len(fired) == 1 and fired[0]["group"] == "match-2",
              f"{len(fired)} fired")

        # disabled event: register returns True but produces no plan
        before = len(planner.pending)
        planner.register("AI_KILLED_SOMETHING", "match-2", 0, 0)
        check("disabled event ignored", len(planner.pending) == before)

        # second kill right after a save gets throttled (ready_at pushed out)
        Clock.now = 24.5
        planner.register("HUNTER_KILLED", "match-3", -20000, 5000)
        plan3 = planner.pending["match-3"]
        check("throttle: plan not ready before min_interval",
              plan3["ready_at"] >= 24.0 + 3.0 - 1e-6)
    finally:
        time.monotonic = real_monotonic


if __name__ == "__main__":
    test_golden_frames()
    test_unauthorized_gate()
    test_control_frames()
    test_planner()
    print(f"\n{len(PASS)} passed, {len(FAIL)} failed")
    sys.exit(1 if FAIL else 0)
